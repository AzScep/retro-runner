/** Every character the mini font can draw, space first. */
export const MINI_CHARSET: string = ' ' + Object.keys(MINI_GLYPHS).join('');

/** Uppercases and replaces characters the font lacks with '?'. */
export function normaliseMini(text: string): string {
  let out = '';
  for (const ch of text.toUpperCase()) {
    out += ch === ' ' || ch === '\n' || ch in MINI_GLYPHS ? ch : '?';
  }
  return out;
}

/** Glyph width in px (0 for space, which only advances). */
export function miniGlyphWidth(ch: string): number {
  if (ch === ' ') return MINI_SPACE_ADVANCE - 1;
  return MINI_GLYPHS[ch]?.[0]?.length ?? 0;
}

/** Width in px of a single line drawn with the mini font (no trailing gap). */
export function miniTextWidth(text: string): number {
  const s = normaliseMini(text);
  let w = 0;
  for (const ch of s) w += miniGlyphWidth(ch) + 1;
  return Math.max(0, w - 1);
}

/** Greedy word wrap for the mini font. Returns lines no wider than `maxWidth` px where possible. */
export function wrapMini(text: string, maxWidth: number): string[] {
  const words = normaliseMini(text)
    .split(/\s+/)
    .filter((w) => w.length > 0);
  const lines: string[] = [];
  let line = '';
  for (const word of words) {
    const candidate = line === '' ? word : `${line} ${word}`;
    if (line !== '' && miniTextWidth(candidate) > maxWidth) {
      lines.push(line);
      line = word;
    } else {
      line = candidate;
    }
  }
  if (line !== '') lines.push(line);
  return lines;
}
